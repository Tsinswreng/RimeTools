namespace RimeTools.Tools;

/// 一條串替換規則: Pattern 匹配、Replacement 替換(手寫引擎執行,不走 System.Text.RegularExpressions)。
/// 語法面(ngaq 三份規則文件實測全集):
///   - 字面文本(含「首一/首二/腹一/腹二/尾一/尾二」等標記、IPA 字符如 ˁ æ ŋ)
///   - `.` 任意單字符; `(.)` 捕獲單字符
///   - `(.*)` / `(.*?)` 捕獲任意串(貪婪/非貪婪)
///   - `[...]` 純字符集(字符列舉,無範圍無 ^)
///   - `(a|b|c)` 交替捕獲
///   - `^`/`$` 錨; `;+` 一次以上(唯一量詞+出現處)
/// 替換側支持 `$1`/`$2`… 捕獲引用;原樣輸出其餘文本。
/// 例(真實規則): Pattern="首一(Y)首二腹一([QTIPHYCN])腹二尾一(.*?)尾二"
///                 Replacement="首一j首二腹一$2腹二尾一$3尾二"
///   輸入「首一Y首二腹一T腹二尾一…尾二」→「首一j首二腹一T腹二尾一…尾二」
public sealed record SrRule(
	/// 匹配模式(上述語法面)。
	str Pattern,
	/// 替換文本($N 引用捕獲)。
	str Replacement
);